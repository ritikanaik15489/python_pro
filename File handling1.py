# Types of path
# Relative Paths: A path relative to the Current Working Directory (CWD) where your Python script is executing.Example: data/file.txt
# Absolute Paths: The full, exact address of a file or directory starting from the root of your file system.Windows example: C:\Users\Name\Documents\file.txt